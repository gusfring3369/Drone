#!/usr/bin/env python3
"""
Generate the Gazebo Harmonic world and the blockage model from config/mission.json,
so the 3D world always matches what the planner uses.

    python3 scripts/generate_world.py
      -> worlds/medical_delivery.sdf
      -> models/blockage.sdf

Frame note: Gazebo uses ENU (x = east, y = north); the config/planner use NED
(north, east). So a building at (north=N, east=E) is placed at Gazebo x=E, y=N.
The iris drone (from ardupilot_gazebo) spawns at the origin = hospital pad.
"""
from __future__ import annotations

import os
import sys

from planner import DEFAULT_CONFIG, ROOT, load_config, obstacles_from_config

WORLD_TEMPLATE = """<?xml version="1.0" ?>
<!-- AUTO-GENERATED by scripts/generate_world.py from config/mission.json - edit the config, not this file. -->
<sdf version="1.9">
  <world name="{world_name}">
    <physics name="1ms" type="ignore">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-navsat-system" name="gz::sim::systems::NavSat"/>

    <scene>
      <ambient>1.0 1.0 1.0</ambient>
      <background>0.8 0.9 1.0</background>
      <sky></sky>
    </scene>

    <!-- Same reference location as ArduPilot SITL's default home (CMAC, Canberra) -->
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model>
      <world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>-35.363262</latitude_deg>
      <longitude_deg>149.165237</longitude_deg>
      <elevation>584</elevation>
      <heading_deg>0</heading_deg>
    </spherical_coordinates>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 100 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>600 600</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>600 600</size></plane></geometry>
          <material>
            <ambient>0.35 0.55 0.3 1</ambient>
            <diffuse>0.35 0.55 0.3 1</diffuse>
          </material>
        </visual>
      </link>
    </model>

{pads}
{buildings}
    <!-- The drone: ArduPilot iris quadcopter from ardupilot_gazebo (needs GZ_SIM_RESOURCE_PATH) -->
    <include>
      <uri>model://iris_with_ardupilot</uri>
      <pose degrees="true">0 0 0.195 0 0 90</pose>
    </include>
  </world>
</sdf>
"""

PAD_TEMPLATE = """    <model name="{name}">
      <static>true</static>
      <pose>{x} {y} 0.01 0 0 0</pose>
      <link name="link">
        <visual name="visual">
          <geometry><cylinder><radius>3</radius><length>0.02</length></cylinder></geometry>
          <material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse></material>
        </visual>
      </link>
    </model>
"""

BOX_MODEL = """    <model name="{name}">
      <static>true</static>
      <pose>{x} {y} 0 0 0 0</pose>
      <link name="link">
        <pose>0 0 {half_h} 0 0 0</pose>
        <collision name="collision">
          <geometry><box><size>{sx} {sy} {h}</size></box></geometry>
        </collision>
        <visual name="visual">
          <geometry><box><size>{sx} {sy} {h}</size></box></geometry>
          <material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse></material>
        </visual>
      </link>
    </model>
"""

BLOCKAGE_TEMPLATE = """<?xml version="1.0" ?>
<!-- AUTO-GENERATED by scripts/generate_world.py: temporary route blockage, spawned/removed at runtime by mission.py -->
<sdf version="1.9">
{model}</sdf>
"""


def box_sdf(name, north, east, size_n, size_e, height, rgb):
    # Gazebo ENU: x = east, y = north -> box size x = east extent, y = north extent
    return BOX_MODEL.format(name=name, x=east, y=north, half_h=height / 2,
                            sx=size_e, sy=size_n, h=height, rgb=rgb)


def main() -> int:
    cfg = load_config(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_CONFIG)

    pads = PAD_TEMPLATE.format(name="hospital_pad", x=cfg["hospital"]["east"], y=cfg["hospital"]["north"],
                               rgb="0.9 0.1 0.1")
    pads += PAD_TEMPLATE.format(name="village_pad", x=cfg["village"]["east"], y=cfg["village"]["north"],
                                rgb="0.1 0.8 0.2")
    buildings = "".join(box_sdf(b.name, b.north, b.east, b.size_n, b.size_e, b.height, "0.55 0.55 0.6")
                        for b in obstacles_from_config(cfg))

    world = WORLD_TEMPLATE.format(world_name=cfg["world_name"], pads=pads, buildings=buildings)
    world_path = os.path.join(ROOT, "worlds", f"{cfg['world_name']}.sdf")
    os.makedirs(os.path.dirname(world_path), exist_ok=True)
    with open(world_path, "w") as f:
        f.write(world)

    blk = cfg["blockage"]
    blockage = BLOCKAGE_TEMPLATE.format(
        model=box_sdf("blockage", 0, 0, blk["size"], blk["size"], blk["height"], "0.95 0.35 0.05"))
    blk_path = os.path.join(ROOT, "models", "blockage.sdf")
    os.makedirs(os.path.dirname(blk_path), exist_ok=True)
    with open(blk_path, "w") as f:
        f.write(blockage)

    print(f"Wrote {world_path}")
    print(f"Wrote {blk_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
